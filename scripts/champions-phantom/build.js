// Packages the user-provided original gun and DFDF's generated presentation:
//   node scripts/champions-phantom/build.js   (npm run build:champions-phantom)
// Output: assets/champions-phantom/dfdf-1/ with manifest.json (sizes + SHA-256).
// Original gun bytes are pinned in source-gun/; Java code is never executed.
"use strict";
const fs = require("node:fs"), path = require("node:path"), crypto = require("node:crypto");
const { encode } = require("./png");
const gun = require("./source-gun"), animation = require("./animation");
const creatures = require("./creatures"), fx = require("./fx"), audio = require("./audio");

const VERSION = "dfdf-1";
// CHAMPIONS_OUT writes elsewhere (the test suite regenerates into a temp folder and compares).
const root = process.env.CHAMPIONS_OUT ? path.resolve(process.env.CHAMPIONS_OUT) : path.resolve(__dirname, "../../assets/champions-phantom", VERSION);
function write(name, bytes) {
  const file = path.join(root, name);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, bytes);
}
const json = (value) => Buffer.from(JSON.stringify(value) + "\n");

function main() {
  const sourceFiles=gun.files(); // Validate all original inputs before replacing the working pack.
  const geo=JSON.parse(sourceFiles.find(f=>f.name.endsWith('.geo.json')).bytes)['minecraft:geometry'][0];
  fs.rmSync(root, { recursive: true, force: true });
  const files = [];
  const add = (name, bytes) => { write(name, bytes); files.push({ name, size: bytes.length, sha256: crypto.createHash("sha256").update(bytes).digest("hex") }); };

  // Copy every authored cube/pivot/UV and original PNG byte without fitting or repainting.
  for(const file of sourceFiles)add(file.name,file.bytes);
  add("animations/phantom_champions_2026.animation.json", json(animation.build()));
  // Finisher creatures.
  for (const [name, built] of Object.entries(creatures.build())) {
    add(`geo/finisher/${name}.geo.json`, json(built.model.json()));
    for (const [texture, canvas] of Object.entries(built.textures)) add(`textures/finisher/${texture}.png`, encode(canvas));
  }
  for (const [name, canvas] of Object.entries(fx.fxTextures())) add(`textures/finisher/fx/${name}.png`, encode(canvas));
  for (const [name, canvas] of Object.entries(fx.bannerTextures())) add(`textures/gui/banner/${name}.png`, encode(canvas));
  const art = fx.gunArt();
  add("textures/vfx/gunart_side.png", encode(art.side));
  add("textures/vfx/gunart_top.png", encode(art.top));
  add("textures/vfx/lick_attacker.png", encode(fx.lick(true)));
  add("textures/vfx/lick_defender.png", encode(fx.lick(false)));
  files.sort((a, b) => a.name.localeCompare(b.name));
  write("manifest.json", json({ version: VERSION, author: "DFDF", generator: "scripts/champions-phantom/build.js", gunSource:{file:gun.provenance.source,sha256:gun.provenance.sourceSha256}, files }));

  // Music: instrument recipes and note sequences (not listed in the visual manifest).
  const music = audio.build();
  write("audio/samples.json", json(music.samples));
  write("audio/kill-sequences.json", json(music.kill));
  write("audio/music-sequences.json", json(music.music));
  write("SOURCE-NOTICE.txt", Buffer.from([
    "Champions Phantom assets for DFDF (13).",
    "",
    "The gun geometry and attacker/defender base/glow textures are copied",
    "byte-for-byte from ChampionsPhantom2026-0.1.0.jar supplied by the user,",
    "who identified themselves as its original creator and requested this use.",
    "Pinned source hashes: scripts/champions-phantom/source-gun/provenance.json.",
    "The remaining presentation is original DFDF work, generated by code in",
    "scripts/champions-phantom/ (npm run build:champions-phantom). The kill,",
    "inspect and finisher music is DFDF's own arrangement, played on instruments",
    "that js/phantom-audio.js synthesizes in the browser. The original Java",
    "classes are not included or executed.",
    "",
  ].join("\n")));
  if (!process.env.CHAMPIONS_OUT) require("./sync-wave").sync(); // keep the kill-coat palettes in js/ matching the painted colours
  console.log(`Champions Phantom ${VERSION}: ${files.length} visual files, original gun ${geo.bones.reduce((n,b)=>n+(b.cubes?.length||0),0)} cubes / ${geo.bones.length} bones`);
}
main();
