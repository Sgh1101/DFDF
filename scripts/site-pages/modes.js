<p>랭크전은 일반전으로만 열립니다. 표적 사격을 뺀 모든 모드의 경기는 경험치와 골드를 줍니다. 처음이라면 <a href="./guide.html">게임 소개</a>에서 한 라운드가 어떻게 흘러가는지 먼저 읽어 보세요.</p>
